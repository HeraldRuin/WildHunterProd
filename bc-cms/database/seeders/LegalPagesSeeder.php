    private function updateFooterLinks(): void
    {
        $setting = Settings::query()->where('name', 'list_widget_footer')->first();
        if (!$setting) {
            return;
        }

        $widgets = json_decode($setting->val, true);
        if (!is_array($widgets)) {
            return;
        }

        $links = [
            'Бронирование и отмена' => '/page/usloviya-bronirovaniya',
            'Политика конфиденциальности' => '/page/privacy-policy',
            'Пользовательское соглашение' => '/page/polzovatelskoe-soglashenie',
        ];

        $labelAliases = [
            'Условия бронирования' => 'Бронирование и отмена',
            'Правила отмены' => 'Пользовательское соглашение',
        ];

        foreach ($widgets as &$widget) {
            if (empty($widget['content']) || !is_string($widget['content'])) {
                continue;
            }

            foreach ($labelAliases as $oldLabel => $newLabel) {
                $widget['content'] = preg_replace(
                    '/(<a href="[^"]*"[^>]*>)\s*' . preg_quote($oldLabel, '/') . '\s*(<\/a>)/u',
                    '$1' . $newLabel . '$2',
                    $widget['content']
                );
            }

            foreach ($links as $label => $url) {
                $widget['content'] = preg_replace(
                    '/<a href="[^"]*"([^>]*)>\s*' . preg_quote($label, '/') . '\s*<\/a>/u',
                    '<a href="' . $url . '"$1>' . $label . '</a>',
                    $widget['content']
                );
            }
        }
        unset($widget);

        Settings::store('list_widget_footer', json_encode($widgets, JSON_UNESCAPED_UNICODE));
    }
